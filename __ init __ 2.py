class Cricketers:
    def __init__(self, name, centuries,):
        self.name = name
        self.centuries = centuries
c1 = Cricketers("Sachin Tendulkar", "100 centuries")
c2 = Cricketers("Riki Ponting", "71 centuries")
c3 = Cricketers("Kane Williamson", "48 centuries")
print(c1.name, c1.centuries)
print(c2.name,  c2.centuries)
print(c3.name,  c3.centuries)