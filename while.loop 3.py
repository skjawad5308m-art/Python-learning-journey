n = int(input("ENTER THE NUMBER :"))
i = 1
while i <= 1000:
    print(i * n )
    i += 1

n2 = int(input("ENTER THE 2ND NUMBER :"))
i2 = 1000
while i2 >= 1 :
    print(i2 / n2)
    i2 -= 1

n3 = int(input("ENTER THE 3RD NUMBER :"))
